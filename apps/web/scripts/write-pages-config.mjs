/**
 * Emits Cloudflare Pages' `_headers` and `_redirects` into dist/ after a build.
 *
 * In the docker-compose deployment Caddy fronts the app: it serves the bundle,
 * proxies /api to the server on the same origin, and sets the security headers
 * (ops/Caddyfile). On Pages there is no proxy — the bundle is static and the API
 * lives on another origin — so those headers have to ship with the build, and
 * the CSP has to name that origin explicitly.
 *
 * Run via `npm run build:pages -w apps/web` with VITE_API_URL set to the API's
 * public base URL (the same value the bundle was compiled against).
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dist = join(dirname(fileURLToPath(import.meta.url)), '..', 'dist');

const apiUrl = process.env.VITE_API_URL?.trim();
if (!apiUrl) {
  console.error(
    'VITE_API_URL is not set. The CSP must name the API origin explicitly, and\n' +
      'the bundle needs the same value, so this is required rather than guessed.\n' +
      'Example: VITE_API_URL=https://sahay-api.example.run npm run build:pages -w apps/web',
  );
  process.exit(1);
}

let api;
try {
  api = new URL(apiUrl);
} catch {
  console.error(`VITE_API_URL is not a valid absolute URL: ${apiUrl}`);
  process.exit(1);
}

// The WebSocket connection goes to the same host over ws/wss (see wsUrl() in
// src/api/client.ts), and CSP treats that as a separate connect-src entry.
const wsOrigin = `${api.protocol === 'https:' ? 'wss' : 'ws'}://${api.host}`;
const connectSrc = ["'self'", api.origin, wsOrigin].join(' ');

const csp = [
  "default-src 'self'",
  "img-src 'self' data:",
  // Vite inlines some styles; matches the policy Caddy serves in the compose path.
  "style-src 'self' 'unsafe-inline'",
  `connect-src ${connectSrc}`,
  "frame-ancestors 'none'",
].join('; ');

const headers = `# Generated by scripts/write-pages-config.mjs — do not edit by hand.
# API origin baked in at build time: ${api.origin}
/*
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: no-referrer
  Permissions-Policy: geolocation=(self), microphone=(), camera=()
  Content-Security-Policy: ${csp}

# Hashed asset filenames are immutable; index.html must never be cached, or a
# deploy leaves browsers loading a stale bundle against a newer API.
/assets/*
  Cache-Control: public, max-age=31536000, immutable

/index.html
  Cache-Control: no-cache
`;

// The app uses history-mode routing, so every unmatched path must serve
// index.html rather than 404 — a reload on /admin or /events/:code would
// otherwise fail. 200 (not 302) keeps the URL intact for the router.
const redirects = `# Generated by scripts/write-pages-config.mjs — do not edit by hand.
/*  /index.html  200
`;

mkdirSync(dist, { recursive: true });
writeFileSync(join(dist, '_headers'), headers);
writeFileSync(join(dist, '_redirects'), redirects);

console.log(`wrote dist/_headers and dist/_redirects (API origin: ${api.origin})`);
